-- Security-definer helper avoids recursive RLS checks on admin_users.
create or replace function public.is_site_admin()
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users au where au.user_id = (select auth.uid())
  );
$$;
revoke all on function public.is_site_admin() from public;
grant execute on function public.is_site_admin() to authenticated;

grant select on public.admin_users to authenticated;

create table if not exists public.player_links (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  category text not null check (char_length(category) between 1 and 60),
  url text not null check (url ~* '^https?://[^[:space:]]+$'),
  description text check (description is null or char_length(description) <= 300),
  logo_url text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.player_links add column if not exists logo_url text;
alter table public.player_links enable row level security;
drop policy if exists "Public can read active links" on public.player_links;
create policy "Public can read active links" on public.player_links
  for select to anon, authenticated using (is_active = true);
drop policy if exists "Only admins can read all links" on public.player_links;
create policy "Only admins can read all links" on public.player_links
  for select to authenticated using ((select public.is_site_admin()));
drop policy if exists "Only admins can insert links" on public.player_links;
create policy "Only admins can insert links" on public.player_links
  for insert to authenticated with check ((select public.is_site_admin()));
drop policy if exists "Only admins can update links" on public.player_links;
create policy "Only admins can update links" on public.player_links
  for update to authenticated using ((select public.is_site_admin())) with check ((select public.is_site_admin()));
drop policy if exists "Only admins can delete links" on public.player_links;
create policy "Only admins can delete links" on public.player_links
  for delete to authenticated using ((select public.is_site_admin()));
create index if not exists player_links_active_created_idx on public.player_links (is_active, created_at desc);
create index if not exists player_links_category_idx on public.player_links (category);

